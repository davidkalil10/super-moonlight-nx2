// Writes shaders.h, the prebuilt civ7 SPIR-V as C arrays for the native renderer.
// Run after `src/renderer/civ7/build.js --install`; the dev repo test fails when it is stale.
import fs from 'node:fs';
import path from 'node:path';
import {loadRenderer} from '../../renderer/civ7/bundle.js';

const STAGES = ['publish', 'videoVertex', 'videoFragment', 'videoStorageFragment', 'uiVertex', 'uiFragment'];

const identifier = (/** @type {string} */ stage) => 'moonlight_spirv_' + stage.replace(/[A-Z]/g, letter => '_' + letter.toLowerCase());

/** @param {Buffer} bytes */
function words(bytes) {
  const lines = [];
  for (let offset = 0; offset < bytes.length; offset += 32) {
    const row = [];
    for (let at = offset; at < Math.min(offset + 32, bytes.length); at += 4)
      row.push('0x' + bytes.readUInt32LE(at).toString(16).padStart(8, '0'));
    lines.push('    ' + row.join(', ') + ',');
  }
  return lines.join('\n');
}

export async function shadersHeader() {
  const {manifest, shaders} = await loadRenderer();
  const parts = ['// Generated by embed-shaders.mjs from src/renderer/civ7/prebuilt. Do not edit.',
    '#pragma once', '', '#include <stdint.h>', '',
    `#define MOONLIGHT_SHADERS_BLOB_SHA256 "${manifest.blob.sha256}"`, ''];
  for (const stage of STAGES) {
    const bytes = shaders[stage];
    parts.push(`static const uint32_t ${identifier(stage)}[${bytes.length / 4}] = {`, words(bytes), '};', '');
  }
  return parts.join('\n');
}

if (process.argv[1] === import.meta.filename) {
  const target = path.join(import.meta.dirname, 'shaders.h');
  fs.writeFileSync(target, await shadersHeader());
  console.log('wrote', target);
}
