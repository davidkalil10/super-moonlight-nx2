#define RANGE_COUNT (sizeof(RANGES) / sizeof(RANGES[0]))
#define EXPANSION_COUNT (sizeof(EXPANSIONS) / sizeof(EXPANSIONS[0]))

static const CaseExpansion *find_expansion(uint32_t code)
{
    size_t low = 0;
    size_t high = EXPANSION_COUNT;
    while (low < high) {
        const size_t middle = low + (high - low) / 2;
        if (EXPANSIONS[middle].code < code)
            low = middle + 1;
        else
            high = middle;
    }

    if (low < EXPANSION_COUNT && EXPANSIONS[low].code == code)
        return &EXPANSIONS[low];
    return NULL;
}

static const CaseRange *find_range(uint32_t code)
{
    size_t low = 0;
    size_t high = RANGE_COUNT;
    while (low < high) {
        const size_t middle = low + (high - low) / 2;
        if (RANGES[middle].last < code)
            low = middle + 1;
        else
            high = middle;
    }

    if (low == RANGE_COUNT || RANGES[low].first > code)
        return NULL;
    if ((code - RANGES[low].first) % RANGES[low].stride != 0)
        return NULL;
    return &RANGES[low];
}

uint32_t moonlightUppercase(uint32_t code, uint32_t upper[MOONLIGHT_UPPERCASE_MAX])
{
    const CaseExpansion *expansion = find_expansion(code);
    if (expansion) {
        for (uint32_t i = 0; i < expansion->count; i++)
            upper[i] = expansion->upper[i];
        return expansion->count;
    }

    const CaseRange *range = find_range(code);
    upper[0] = range ? (uint32_t)((int64_t)code + range->delta) : code;
    return 1;
}
