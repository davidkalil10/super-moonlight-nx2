#!/usr/bin/env python3
"""Builds the shaders the runtime embeds: the six-stage bundle and the UI text shader.

  build-shaders.py --directory NEW [--install]   compile into NEW, then copy to runtime/prebuilt
  build-shaders.py --check                       compare runtime/prebuilt with the sources

Compiling needs glslc and spirv-val; the check needs neither. layout.glsl comes from the
storage layout below, the same one core/src/frame.rs and the ui crate use.
"""

import argparse
import hashlib
import json
from pathlib import Path
import platform
import re
import shutil
import struct
import subprocess

from build import BUILDS, digest, git, output, write_json


ROOT = Path(__file__).resolve().parent
SHADERS = ROOT / "runtime/shaders"
PREBUILT = ROOT / "runtime/prebuilt"
BUNDLE = "shaders.bin"
TEXT = "ui-text"
# Bundle entry names in the order runtime/build.rs reads them.
STAGES = {
    "publish": "publish.comp",
    "video-vertex": "video.vert",
    "video-fragment": "video.frag",
    "video-storage-fragment": "video-storage.frag",
    "ui-vertex": "ui.vert",
    "ui-fragment": "ui.frag",
}

WIDTH, HEIGHT = 1920, 1080
ABI = 2
NATIVE_ABI = 0x484E5633
UI_MAGIC = 0x49554248
MODE_NATIVE = 3
INPUT_BYTES = 4096
# A slot holds a 3840x2160 NV12 frame with 16 rows of padding.
FRAME_BYTES = 3840 * 2176 * 3 // 2
FRAME_COUNT = 3
# The frames follow the control page and the eight ring slots the offsets still count.
FRAMES_OFFSET = 0x10000 + 8 * 9 * 0x8000
UI_OFFSET = FRAMES_OFFSET + FRAME_COUNT * FRAME_BYTES + 4096
UI_PAGE_BYTES = 4 * 1024 * 1024
UI_PAGES = 2
STORAGE_BYTES = UI_OFFSET + UI_PAGES * UI_PAGE_BYTES
UI_INSTANCES = 128
VIDEO_SLOTS = 2
# The badge pixels live in the third frame slot.
BADGE_OFFSET = FRAMES_OFFSET + 2 * FRAME_BYTES
BADGE_BYTES = 960 * 64 * 4

# Byte offsets in storage; the shaders index it by word.
CONTROL = {
    "mode": 8, "current": 12, "size": 16,
    "currentStride": 64, "currentSliceHeight": 68, "currentColor": 72,
    "nativeReady": 24, "nativeApplied": 32,
    "nativeSequence": 256, "nativeIndex": 260, "nativeWidth": 264, "nativeHeight": 268,
    "nativeStride": 272, "nativeSliceHeight": 276, "nativeColor": 280, "nativeCommit": 284,
    "frameCounter": 512,
}
UI = {name: 0xC000 + 4 * index for index, name in enumerate((
    "uiMagic", "uiEpoch", "uiSequence", "uiPage", "uiApplied", "uiCursor", "uiOverlay",
    "uiTouchItem", "cmdSequence", "cmdOp", "cmdItem", "cmdValue", "cmdPage", "cmdEpoch",
    "uiShown", "uiEdit", "hostAck", "hostBusy", "uiFilter", "uiCheck", "uiSumValue", "uiSumSeq"))}
INPUT = {"pad": 0, "touch": 128, "previousButtons": 784, "chordFrames": 788,
         "stickRepeat": 792, "touchHeld": 796}
VIDEO_BASE = 0xB000
VIDEO_SLOT_BYTES = 32
VIDEO_SLOT = {"sequence": 0, "width": 4, "height": 8, "stride": 12, "sliceHeight": 16, "color": 20}
BADGE = {"visible": 0xB100, "x": 0xB104, "y": 0xB108, "width": 0xB10C, "height": 0xB110}
TARGET = {"width": 0xB120, "height": 0xB124, "backingWidth": 0xB128, "backingHeight": 0xB12C}

MAGIC = 0x42414C4D
SPIRV_MAGIC = 0x07230203
REGIONS = (("input", INPUT_BYTES), ("storage", STORAGE_BYTES))
FIXED_BYTES, REGION_BYTES, ENTRY_BYTES, ALIGNMENT = 32, 16, 80, 16
ENTRIES_AT = FIXED_BYTES + len(REGIONS) * REGION_BYTES
CHECKSUM_AT = 24


def words(prefix, table):
    def constant(name):
        return re.sub("[A-Z]", lambda letter: "_" + letter.group(), name).upper()
    return [f"const uint {prefix}{constant(name)} = {offset // 4}u;" for name, offset in table.items()]


def layout():
    """layout.glsl. The manifests record its hash, so the first line stays as it was."""
    return "\n".join([
        "// Generated by civ7/layout.js.",
        *words("", {**CONTROL, **UI}), *words("INPUT_", INPUT), *words("SLOT_", VIDEO_SLOT),
        *words("BADGE_", BADGE), *words("TARGET_", TARGET),
        f"const uint VIDEO_BASE = {VIDEO_BASE // 4}u;",
        f"const uint VIDEO_SLOT_WORDS = {VIDEO_SLOT_BYTES // 4}u;",
        f"const uint BADGE_PIXELS = {BADGE_OFFSET // 4}u;",
        f"const uint FRAME_BYTES = {FRAME_BYTES}u;",
        f"const uint FRAME_COUNT = {FRAME_COUNT}u;",
        f"const uint FRAMES_OFFSET = {FRAMES_OFFSET}u;",
        f"const uint MODE_NATIVE = {MODE_NATIVE}u;",
        f"const uint UI_BASE = {UI_OFFSET // 4}u;",
        f"const uint UI_PAGE_WORDS = {UI_PAGE_BYTES // 4}u;",
        f"const uint UI_PROTOCOL_MAGIC = {UI_MAGIC}u;",
        f"const uint NATIVE_ABI = {NATIVE_ABI}u;",
        f"const vec2 DISPLAY_SIZE = vec2({WIDTH}, {HEIGHT});",
        ""])


def contract():
    return {
        "abi": ABI, "nativeABI": NATIVE_ABI,
        "viewport": {"width": WIDTH, "height": HEIGHT},
        "buffers": dict(REGIONS),
        "video": {"frameBytes": FRAME_BYTES, "frameCount": FRAME_COUNT, "framesOffset": FRAMES_OFFSET,
                  "slots": VIDEO_SLOTS,
                  "slotWords": {"base": VIDEO_BASE, "slotBytes": VIDEO_SLOT_BYTES, **VIDEO_SLOT},
                  "sampling": ["texel-buffer", "storage-bilinear"]},
        "ui": {"offset": UI_OFFSET, "pageBytes": UI_PAGE_BYTES, "pages": UI_PAGES, "vertices": 6,
               "instances": UI_INSTANCES, "blending": "source-alpha"},
        "badge": {"instance": UI_INSTANCES, "words": BADGE, "offset": BADGE_OFFSET, "bytes": BADGE_BYTES},
        "bindings": {"input": 0, "storage": 1, "luma": 2, "chroma": 3},
        "control": CONTROL, "uiControl": UI, "input": INPUT, "initialState": "zero",
    }


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def checksum(data):
    """FNV-1a over little-endian words, a short tail zero padded, as runtime/build.rs checks it."""
    result = 2166136261
    for (word,) in struct.iter_unpack("<I", data + bytes(-len(data) % 4)):
        result = ((result ^ word) * 16777619) & 0xFFFFFFFF
    return result


def align(value):
    return -(-value // ALIGNMENT) * ALIGNMENT


def pack(shaders):
    """The bundle: a header, the two buffer sizes, one entry per stage, then the SPIR-V."""
    if list(shaders) != list(STAGES):
        raise ValueError("The shaders do not match the bundle's stages")
    for name, data in shaders.items():
        if len(data) < 20 or len(data) % 4 or struct.unpack_from("<I", data)[0] != SPIRV_MAGIC:
            raise ValueError(f"{name} is not SPIR-V")
    header_bytes = align(ENTRIES_AT + len(shaders) * ENTRY_BYTES)
    offsets = []
    end = header_bytes
    for data in shaders.values():
        offsets.append(end)
        end = align(end + len(data))
    blob = bytearray(end)
    struct.pack_into("<6I", blob, 0, MAGIC, 1, header_bytes, end, len(REGIONS), len(shaders))
    for index, (name, size) in enumerate(REGIONS):
        struct.pack_into("<12sI", blob, FIXED_BYTES + index * REGION_BYTES, name.encode(), size)
    for index, (offset, (name, data)) in enumerate(zip(offsets, shaders.items())):
        struct.pack_into("<24s5I4x32s", blob, ENTRIES_AT + index * ENTRY_BYTES, name.encode(),
                         offset, len(data), 0, 0, checksum(data), hashlib.sha256(data).digest())
        blob[offset:offset + len(data)] = data
    struct.pack_into("<I", blob, CHECKSUM_AT, checksum(bytes(blob[:header_bytes])))
    return bytes(blob)


def unpack(blob):
    shaders = {}
    for index in range(len(STAGES)):
        name, offset, size = struct.unpack_from("<24s2I", blob, ENTRIES_AT + index * ENTRY_BYTES)
        shaders[name.rstrip(b"\0").decode()] = blob[offset:offset + size]
    return shaders


def bundle_sources():
    """Hashes of what the bundle is compiled from: every shader source but the text wrapper."""
    hashes = {path.name: digest(path) for path in sorted(SHADERS.iterdir())
              if path.name != f"{TEXT}.frag"}
    hashes["layout.glsl"] = sha256(layout().encode())
    return hashes


def bundle_manifest(blob):
    return {"format": "moonlight.civ7.renderer", "version": 2, "contract": contract(),
            "blob": {"path": BUNDLE, "bytes": len(blob), "sha256": sha256(blob)},
            "sources": bundle_sources()}


def text_sources():
    hashes = {name: digest(SHADERS / name) for name in (f"{TEXT}.frag", "ui.frag", "storage.glsl")}
    hashes["layout.glsl"] = sha256(layout().encode())
    return hashes


def compile_shader(source, target, commands, log):
    for command in (["glslc", "-O", "--target-env=vulkan1.0", "-I", target.parent, "-I", SHADERS,
                     source, "-o", target],
                    ["spirv-val", "--target-env", "vulkan1.0", target]):
        commands.append([str(word) for word in command])
        subprocess.run(command, stdout=log, stderr=subprocess.STDOUT, check=True)
    return target.read_bytes()


def build(directory, install):
    if not directory.is_absolute() or BUILDS not in directory.parents or directory.exists():
        raise ValueError(f"Use a new build directory under {BUILDS}")
    directory.mkdir()
    (directory / "layout.glsl").write_text(layout())
    commands = []
    text = directory / f"{TEXT}.spv"
    with (directory / "build.log").open("w") as log:
        shaders = {name: compile_shader(SHADERS / filename, directory / f"{filename}.spv", commands, log)
                   for name, filename in STAGES.items()}
        # The text shader wraps ui.frag's main, so it includes ui.frag without its version line.
        base = (SHADERS / "ui.frag").read_text()
        if not base.startswith("#version 450\n"):
            raise ValueError("Unexpected version line in ui.frag")
        (directory / "ui-base.frag").write_text(base.removeprefix("#version 450\n"))
        shutil.copy2(SHADERS / f"{TEXT}.frag", directory)
        text_commands = []
        compile_shader(directory / f"{TEXT}.frag", text, text_commands, log)

    blob = pack(shaders)
    (directory / BUNDLE).write_bytes(blob)
    write_json(directory / "renderer.json", bundle_manifest(blob))
    compiler = output("glslc", "--version")
    branch = git("branch", "--show-current")
    write_json(directory / f"{TEXT}.json", {
        "format": f"moonlight.rust.{TEXT}", "version": 1, "builder": platform.node(),
        "source_branch": branch, "commands": text_commands, "compiler": compiler,
        "sources": text_sources(),
        "shader": {"path": text.name, "bytes": text.stat().st_size, "sha256": digest(text)},
        "scope": "Text branch separated; original colors, sampled alpha and blending retained"})
    write_json(directory / "BUILD-INFO.json", {
        "source_revision": git("rev-parse", "HEAD"), "source_branch": branch,
        "dirty": bool(git("status", "--porcelain", "--", ROOT)),
        "builder": platform.node(), "target": "SPIR-V for Vulkan 1.0", "compiler": compiler,
        "commands": commands + text_commands,
        "shader_bytes": {name: len(data) for name, data in shaders.items()},
        "installed": install})
    for name in (BUNDLE, f"{TEXT}.spv"):
        same = digest(directory / name) == digest(PREBUILT / name)
        print(f"{name}: {digest(directory / name)}, {'same as' if same else 'differs from'} prebuilt")
    if install:
        for name in (BUNDLE, "renderer.json", f"{TEXT}.spv", f"{TEXT}.json"):
            shutil.copy2(directory / name, PREBUILT / name)


def check():
    blob = (PREBUILT / BUNDLE).read_bytes()
    if pack(unpack(blob)) != blob:
        raise ValueError(f"{BUNDLE} is not what the packer writes")
    manifest = json.dumps(bundle_manifest(blob), indent=2) + "\n"
    if (PREBUILT / "renderer.json").read_text() != manifest:
        raise ValueError("renderer.json differs from the bundle, the layout or the shader sources")
    record = json.loads((PREBUILT / f"{TEXT}.json").read_text())
    if {Path(name).name: value for name, value in record["sources"].items()} != text_sources():
        raise ValueError(f"{TEXT}.json differs from the shader sources")
    shader = PREBUILT / record["shader"]["path"]
    if record["shader"] != {"path": shader.name, "bytes": shader.stat().st_size, "sha256": digest(shader)}:
        raise ValueError(f"{TEXT}.spv differs from its record")
    print("prebuilt shaders match the sources")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--directory", type=Path, help=f"new build directory under {BUILDS}")
    parser.add_argument("--install", action="store_true", help="copy the result to runtime/prebuilt")
    parser.add_argument("--check", action="store_true",
                        help="compare runtime/prebuilt with the sources instead of compiling")
    args = parser.parse_args()
    if args.check == bool(args.directory):
        parser.error("give --directory or --check")
    if args.check:
        check()
    else:
        build(args.directory, args.install)


if __name__ == "__main__":
    main()
