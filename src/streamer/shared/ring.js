/**
 * Layout of the Moonlight app's private storage (binding 1): control words, the frame ring,
 * the decoded frames and the UI pages. ring.glsl is generated from it; see README.md.
 */
const SLOTS = 8;
const EXCHANGE_BYTES = 0x8000;
const SLOT_EXCHANGES = 9;
const SLOT_BYTES = SLOT_EXCHANGES * EXCHANGE_BYTES;
const CONTROL_BYTES = 0x10000;
const RING_OFFSET = CONTROL_BYTES;
const FRAME_STRIDE = 1920;
const FRAME_HEIGHT = 1088;
const LUMA_BYTES = FRAME_STRIDE * FRAME_HEIGHT;
const CHROMA_BYTES = (FRAME_STRIDE / 2) * (FRAME_HEIGHT / 2);
const FRAME_BYTES = LUMA_BYTES + 2 * CHROMA_BYTES;
const FRAMES_OFFSET = RING_OFFSET + SLOTS * SLOT_BYTES;
const NATIVE_FRAMES = 3;
/** One spare page: unaligned 12-byte loads in the shader may read a word past the last frame. */
const SPARE_BYTES = 4096;
/** The console UI pages (U2) follow the spare page: two buffers the host publishes into. */
const UI_OFFSET = FRAMES_OFFSET + NATIVE_FRAMES * FRAME_BYTES + SPARE_BYTES;
const UI_PAGES = 2;
const UI_PAGE_BYTES = 4 * 1024 * 1024;
const MEMORY_BYTES = UI_OFFSET + UI_PAGES * UI_PAGE_BYTES;
/** Size of the build-time test card keyframe placed in the initial memory image. */
const TEST_CARD = [640, 352];
const TEST_CARD_SEQUENCE = SLOTS;
/** Byte offsets of the control words; written[] is one word per macroblock from its offset. */
const CONTROL = {
  applied: 0,
  applyCount: 4,
  mode: 8,
  current: 12,
  size: 16,
  hbv1Slot: 20,
  nativeReady: 24,
  nativeApplied: 32,
  currentStride: 64,
  currentSliceHeight: 68,
  currentColor: 72,
  nativeSequence: 256,
  nativeIndex: 260,
  nativeWidth: 264,
  nativeHeight: 268,
  nativeStride: 272,
  nativeSliceHeight: 276,
  nativeColor: 280,
  nativeCommit: 284,
  written: 1024
};
/**
 * Byte offsets of the console UI block in the control page, above written[]. The host owns
 * uiMagic..uiPage and hostAck/hostBusy; the compute shader owns uiApplied..cmdEpoch. See team
 * note `moonlight-ui-design.md`, "Memory and words".
 */
const UI_BLOCK = 0xc000;
const UI = {
  uiMagic: UI_BLOCK,
  uiEpoch: UI_BLOCK + 4,
  uiSequence: UI_BLOCK + 8,
  uiPage: UI_BLOCK + 12,
  uiApplied: UI_BLOCK + 16,
  uiCursor: UI_BLOCK + 20,
  uiOverlay: UI_BLOCK + 24,
  uiTouchItem: UI_BLOCK + 28,
  cmdSequence: UI_BLOCK + 32,
  cmdOp: UI_BLOCK + 36,
  cmdItem: UI_BLOCK + 40,
  cmdValue: UI_BLOCK + 44,
  cmdPage: UI_BLOCK + 48,
  cmdEpoch: UI_BLOCK + 52,
  uiShown: UI_BLOCK + 56,
  hostAck: UI_BLOCK + 64,
  hostBusy: UI_BLOCK + 68
};
const UI_MAGIC = 0x49554248;
/** Command operations the compute shader forwards; the host's state machine interprets them. */
const UI_OP = {a: 1, b: 2, x: 3, y: 4, adjust: 5, chord: 6};
const MODE = {none: 0, hbv1: 1, hbv2: 2, native: 3};
const NATIVE_ABI = 0x484e5633;
/** Compute shader workgroup size. */
const LOCAL_SIZE = 512;
const FNV_OFFSET_BASIS = 2166136261;
const FNV_PRIME = 16777619;

/**
 * Byte offset of the ring slot that holds a sequence.
 * @param {number} sequence
 * @returns {number}
 */
function slotOffset(sequence) {
  return RING_OFFSET + (sequence % SLOTS) * SLOT_BYTES;
}

/**
 * Byte offset of frame buffer `index`.
 * @param {number} index
 * @returns {number}
 */
function frameOffset(index) {
  return FRAMES_OFFSET + index * FRAME_BYTES;
}

/**
 * 32-bit FNV-1a over whole words: the sequence, then the native frame fields.
 * @param {number} sequence
 * @param {number[]} fields
 * @returns {number}
 */
function nativeChecksum(sequence, fields) {
  let checksum = FNV_OFFSET_BASIS;
  for (const value of [sequence, ...fields])
    checksum = Math.imul(checksum ^ value, FNV_PRIME) >>> 0;
  return checksum;
}

/** camelCase control name to its CONTROL_SNAKE_CASE GLSL constant. */
function controlConstant(name) {
  return 'CONTROL_' + name.replace(/[A-Z]/g, letter => '_' + letter).toUpperCase();
}

/**
 * One GLSL word-offset constant per byte offset in `offsets`.
 * @param {Record<string, number>} offsets
 * @returns {string}
 */
function wordConstants(offsets) {
  return Object.entries(offsets)
    .map(([name, offset]) => `const uint ${controlConstant(name)} = ${offset / 4}u;`)
    .join('\n');
}

/**
 * GLSL constants for the ring, frame and control layout; control offsets are in words.
 * @returns {string}
 */
function glsl() {
  const words = wordConstants(CONTROL);
  const ui = wordConstants(UI);

  return `// Generated by tools/moonlight/ring.js.
const uint RING_SLOTS = ${SLOTS}u;
const uint RING_BASE = ${RING_OFFSET / 4}u;
const uint RING_SLOT_WORDS = ${SLOT_BYTES / 4}u;
const uint RING_EXCHANGE_BYTES = ${EXCHANGE_BYTES}u;
const uint FRAME_STRIDE = ${FRAME_STRIDE}u;
const uint FRAME_LUMA_BYTES = ${LUMA_BYTES}u;
const uint FRAME_CHROMA_BYTES = ${CHROMA_BYTES}u;
const uint FRAME_BYTES = ${FRAME_BYTES}u;
const uint NATIVE_FRAMES = ${NATIVE_FRAMES}u;
const uint FRAMES_OFFSET = ${FRAMES_OFFSET}u;
const uint MODE_HBV1 = ${MODE.hbv1}u;
const uint MODE_HBV2 = ${MODE.hbv2}u;
const uint MODE_NATIVE = ${MODE.native}u;
const uint NATIVE_ABI = ${NATIVE_ABI}u;
#define HBV2_LOCAL_SIZE ${LOCAL_SIZE}
${words}
const uint UI_BASE = ${UI_OFFSET / 4}u;
const uint UI_PAGE_WORDS = ${UI_PAGE_BYTES / 4}u;
const uint UI_MAGIC = ${UI_MAGIC}u;
${ui}
`;
}

/**
 * Reads a private-memory image into the planes of the frame the fragment shader would show
 * (for desktop checks against the JS decoder).
 * @param {Buffer} memory
 * @param {number} width
 * @param {number} height
 */
function readFrame(memory, width, height) {
  const current = memory.readUInt32LE(CONTROL.current),
    base = frameOffset(current),
    frame = {width, height};

  const plane = (offset, w, h, stride) => {
    const out = new Uint8Array(w * h);
    for (let y = 0; y < h; y++) {
      const start = base + offset + y * stride;
      memory.copy(out, y * w, start, start + w);
    }
    return out;
  };

  frame.y = plane(0, width, height, FRAME_STRIDE);
  frame.cb = plane(LUMA_BYTES, width / 2, height / 2, FRAME_STRIDE / 2);
  frame.cr = plane(LUMA_BYTES + CHROMA_BYTES, width / 2, height / 2, FRAME_STRIDE / 2);

  return frame;
}

