// Writes src/console-layout.h for hbmoonlight-host from the JS sources of truth:
// the app ring (apps/moonlight/ring.cjs), the launcher state buffer, the
// controller/touch decoders and the verified AudioOut symbol table. The header
// is committed because the build container has no Node; host-layout.test.cjs
// fails when it is stale.
// Usage: node tools/moonlight/helper/generate-layout.cjs [--check]
const fs = require('node:fs');
const path = require('node:path');
const ring = require('../../../apps/moonlight/ring.cjs');
const {STATE} = require('../../../homebrew-launcher/state-layout.cjs');
const {NPAD_BYTES} = require('../controller.cjs');
const {TOUCH_BYTES, PANEL, MAX_POINTS} = require('../touch.cjs');
const symbols = require('../../../homebrew-launcher/audio-symbols.json');
const sdkImage = require('../../../smilebasic/reference/sdk-checks.cjs');

const OUTPUT = path.join(__dirname, 'src/console-layout.h');
const SDK_ALLOCATE = 5732112;
const AUDIO = [
  ['AUDIO_INITIALIZE_PARAMETER', 'InitializeAudioOutParameter'],
  ['AUDIO_OPEN_DEFAULT', 'OpenDefaultAudioOutEPNS0_8AudioOutER'],
  ['AUDIO_SAMPLE_RATE', 'GetAudioOutSampleRate'],
  ['AUDIO_CHANNEL_COUNT', 'GetAudioOutChannelCount'],
  ['AUDIO_SAMPLE_FORMAT', 'GetAudioOutSampleFormat'],
  ['AUDIO_SET_BUFFER_INFO', 'SetAudioOutBufferInfo'],
  ['AUDIO_GET_RELEASED', 'GetReleasedAudioOutBuffer'],
  ['AUDIO_APPEND', 'AppendAudioOutBuffer'],
  ['AUDIO_START', 'StartAudioOut'],
  ['AUDIO_STOP', 'StopAudioOut'],
  ['AUDIO_FLUSH', 'FlushAudioOutBuffers'],
  ['AUDIO_BUFFER_COUNT', 'GetAudioOutBufferCount'],
  ['AUDIO_CLOSE', 'CloseAudioOut']
];

function audioEntry([constant, name]) {
  const matches = symbols.filter(s => s.name.includes(name));
  if (matches.length !== 1) throw Error('Ambiguous audio symbol ' + name);
  const {offset, size} = matches[0];
  const hex = sdkImage.bytes(offset, Math.min(32, size)).toString('hex');
  return `  [${constant}] = {"${name}", ${offset}u, "${hex}"},`;
}

function render() {
  const constants = AUDIO.map(([constant]) => `  ${constant},`).join('\n');
  return `/* Generated by tools/moonlight/helper/generate-layout.cjs; do not edit. */
#pragma once

#define RING_SLOTS ${ring.SLOTS}u
#define RING_SLOT_BYTES ${ring.SLOT_BYTES}u
#define RING_OFFSET ${ring.RING_OFFSET}u
#define RING_MEMORY_BYTES ${ring.MEMORY_BYTES}u
#define RING_CONTROL_APPLIED ${ring.CONTROL.applied}u

#define STATE_TOUCH ${STATE.touch}u
#define NPAD_BYTES ${NPAD_BYTES}u
#define TOUCH_BYTES ${TOUCH_BYTES}u
#define TOUCH_MAX_POINTS ${MAX_POINTS}
#define TOUCH_PANEL_WIDTH ${PANEL.width}
#define TOUCH_PANEL_HEIGHT ${PANEL.height}

#define SDK_ALLOCATE ${SDK_ALLOCATE}u

struct sdk_function {
  const char *name;
  unsigned offset;
  const char *hex;
};

enum audio_function {
${constants}
  AUDIO_FUNCTION_COUNT
};

static const struct sdk_function audio_functions[AUDIO_FUNCTION_COUNT] = {
${AUDIO.map(audioEntry).join('\n')}
};
`;
}

if (require.main === module) {
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(OUTPUT, 'utf8') !== render()) {
      console.error(OUTPUT + ' is stale; run generate-layout.cjs');
      process.exitCode = 1;
    }
  } else {
    fs.writeFileSync(OUTPUT, render());
    console.log(OUTPUT);
  }
}

module.exports = {render, OUTPUT};
