/**
 * Writes src/console-layout.h for hbmoonlight-host from the JS sources of truth: the app ring
 * (tools/moonlight/ring.js), the launcher state buffer, the controller/touch decoders and the
 * verified AudioOut symbol table. The header is committed because the build container has no
 * Node; host-layout.test.cjs fails when it is stale.
 *
 * Usage: node tools/moonlight/helper/generate-layout.js [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import * as ring from '../ring.js';
import {STATE} from '../../../../hbl-platform/sdk/host/layout.js';
import {NPAD_BYTES} from '../controller.js';
import {TOUCH_BYTES, PANEL, MAX_POINTS} from '../touch.js';
import symbols from '../../../../hbl-platform/sdk/native/audio-symbols.json' with {type: 'json'};
import {referenceBytes} from '../../../../hbl-platform/smilebasic/engine/lib/sdk.js';
import {ALLOCATE as SDK_ALLOCATE} from '../../../../hbl-platform/sdk/native/allocate.js';
import {isMain} from '../../../../hbl-platform/sdk/cli.js';

const OUTPUT = path.join(import.meta.dirname, 'src/console-layout.h');
/** Each AudioOut function the helper calls: its C enum constant and a unique symbol substring. */
const AUDIO = [
  ['AUDIO_INITIALIZE_PARAMETER', 'InitializeAudioOutParameter'],
  ['AUDIO_OPEN_DEFAULT', 'OpenDefaultAudioOutEPNS0_8AudioOutER'],
  ['AUDIO_SAMPLE_RATE', 'GetAudioOutSampleRate'],
  ['AUDIO_CHANNEL_COUNT', 'GetAudioOutChannelCount'],
  ['AUDIO_SAMPLE_FORMAT', 'GetAudioOutSampleFormat'],
  ['AUDIO_SET_BUFFER_INFO', 'SetAudioOutBufferInfo'],
  ['AUDIO_GET_RELEASED', 'GetReleasedAudioOutBuffer'],
  ['AUDIO_APPEND', 'AppendAudioOutBuffer'],
  ['AUDIO_START', 'StartAudioOut'],
  ['AUDIO_STOP', 'StopAudioOut'],
  ['AUDIO_FLUSH', 'FlushAudioOutBuffers'],
  ['AUDIO_BUFFER_COUNT', 'GetAudioOutBufferCount'],
  ['AUDIO_CLOSE', 'CloseAudioOut']
];
/** The helper checks this many leading bytes of each function against the SDK image. */
const SIGNATURE_BYTES = 32;

/**
 * The audio_functions[] initializer for one function: its name, SDK offset and the hex of its
 * first bytes.
 * @param {[string, string]} entry
 * @returns {string}
 */
function audioEntry([constant, name]) {
  const matches = symbols.filter(s => s.name.includes(name));
  if (matches.length !== 1) throw Error('Ambiguous audio symbol ' + name);
  const {offset, size} = matches[0];
  const hex = referenceBytes(offset, Math.min(SIGNATURE_BYTES, size)).toString('hex');
  return `  [${constant}] = {"${name}", ${offset}u, "${hex}"},`;
}

/**
 * The header text.
 * @returns {string}
 */
function render() {
  const constants = AUDIO.map(([constant]) => `  ${constant},`).join('\n');
  return `/* Generated by tools/moonlight/helper/generate-layout.cjs; do not edit. */
#pragma once

#define RING_SLOTS ${ring.SLOTS}u
#define RING_SLOT_BYTES ${ring.SLOT_BYTES}u
#define RING_OFFSET ${ring.RING_OFFSET}u
#define RING_MEMORY_BYTES ${ring.MEMORY_BYTES}u
#define RING_CONTROL_APPLIED ${ring.CONTROL.applied}u

#define STATE_TOUCH ${STATE.touch}u
#define NPAD_BYTES ${NPAD_BYTES}u
#define TOUCH_BYTES ${TOUCH_BYTES}u
#define TOUCH_MAX_POINTS ${MAX_POINTS}
#define TOUCH_PANEL_WIDTH ${PANEL.width}
#define TOUCH_PANEL_HEIGHT ${PANEL.height}

#define SDK_ALLOCATE ${SDK_ALLOCATE}u

struct sdk_function {
  const char *name;
  unsigned offset;
  const char *hex;
};

enum audio_function {
${constants}
  AUDIO_FUNCTION_COUNT
};

static const struct sdk_function audio_functions[AUDIO_FUNCTION_COUNT] = {
${AUDIO.map(audioEntry).join('\n')}
};
`;
}

/** Fails when the committed header differs from what render() produces. */
function check() {
  if (fs.readFileSync(OUTPUT, 'utf8') !== render()) {
    console.error(OUTPUT + ' is stale; run generate-layout.js');
    process.exitCode = 1;
  }
}

function write() {
  fs.writeFileSync(OUTPUT, render());
  console.log(OUTPUT);
}

if (isMain(import.meta)) {
  if (process.argv.includes('--check')) check();
  else write();
}

export {render, OUTPUT};
