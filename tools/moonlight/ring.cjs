// Private storage (binding 1) of the Moonlight app:
//   control  64 KiB  words written by the compute shader (last applied
//                    sequence, display mode, ...) and written[], the apply
//                    count at which each HBV2 macroblock was last coded
//   ring     8 slots of 9 exchanges; the host writes slot (sequence % SLOTS)
//            with an HBV1 or HBV2 frame
//   frames   three 1920x1088 4:2:0 YCbCr frames; HBV2 uses the first two
// The compute shader applies slots in sequence order and the fragment shader
// only samples the result (or, for HBV1, decodes the chosen slot per pixel).
const SLOTS = 8;
const EXCHANGE_BYTES = 0x8000;
const SLOT_BYTES = 9 * EXCHANGE_BYTES;
const CONTROL_BYTES = 0x10000;
const RING_OFFSET = CONTROL_BYTES;
const FRAME_STRIDE = 1920;
const FRAME_HEIGHT = 1088;
const LUMA_BYTES = FRAME_STRIDE * FRAME_HEIGHT;
const CHROMA_BYTES = (FRAME_STRIDE / 2) * (FRAME_HEIGHT / 2);
const FRAME_BYTES = LUMA_BYTES + 2 * CHROMA_BYTES;
const FRAMES_OFFSET = RING_OFFSET + SLOTS * SLOT_BYTES;
// One spare page: unaligned 12-byte loads in the shader may read a word past
// the last frame.
const NATIVE_FRAMES = 3;
const MEMORY_BYTES = FRAMES_OFFSET + NATIVE_FRAMES * FRAME_BYTES + 4096;
const TEST_CARD = [640, 352];
const TEST_CARD_SEQUENCE = SLOTS;
const CONTROL = {
  applied: 0,
  applyCount: 4,
  mode: 8,
  current: 12,
  size: 16,
  hbv1Slot: 20,
  nativeReady: 24,
  nativeApplied: 32,
  currentStride: 64,
  currentSliceHeight: 68,
  currentColor: 72,
  nativeSequence: 256,
  nativeIndex: 260,
  nativeWidth: 264,
  nativeHeight: 268,
  nativeStride: 272,
  nativeSliceHeight: 276,
  nativeColor: 280,
  nativeCommit: 284,
  written: 1024
};
const MODE = {none: 0, hbv1: 1, hbv2: 2, native: 3};
const NATIVE_ABI = 0x484e5633;
const LOCAL_SIZE = 1024;

function slotOffset(sequence) {
  return RING_OFFSET + (sequence % SLOTS) * SLOT_BYTES;
}

function frameOffset(index) {
  return FRAMES_OFFSET + index * FRAME_BYTES;
}

function nativeChecksum(sequence, fields) {
  let checksum = 2166136261;
  for (const value of [sequence, ...fields])
    checksum = Math.imul(checksum ^ value, 16777619) >>> 0;
  return checksum;
}

function glsl() {
  const words = Object.entries(CONTROL)
    .map(([name, offset]) => {
      const constant = name.replace(/[A-Z]/g, letter => '_' + letter).toUpperCase();
      return `const uint CONTROL_${constant} = ${offset / 4}u;`;
    })
    .join('\n');
  return `// Generated by tools/moonlight/ring.cjs.
const uint RING_SLOTS = ${SLOTS}u;
const uint RING_BASE = ${RING_OFFSET / 4}u;
const uint RING_SLOT_WORDS = ${SLOT_BYTES / 4}u;
const uint RING_EXCHANGE_BYTES = ${EXCHANGE_BYTES}u;
const uint FRAME_STRIDE = ${FRAME_STRIDE}u;
const uint FRAME_LUMA_BYTES = ${LUMA_BYTES}u;
const uint FRAME_CHROMA_BYTES = ${CHROMA_BYTES}u;
const uint FRAME_BYTES = ${FRAME_BYTES}u;
const uint NATIVE_FRAMES = ${NATIVE_FRAMES}u;
const uint FRAMES_OFFSET = ${FRAMES_OFFSET}u;
const uint MODE_HBV1 = ${MODE.hbv1}u;
const uint MODE_HBV2 = ${MODE.hbv2}u;
const uint MODE_NATIVE = ${MODE.native}u;
const uint NATIVE_ABI = ${NATIVE_ABI}u;
#define HBV2_LOCAL_SIZE ${LOCAL_SIZE}
${words}
`;
}

// Reads a private-memory image into the planes of the frame the fragment
// shader would show (for desktop checks against the JS decoder).
function readFrame(memory, width, height) {
  const control = memory.readUInt32LE(CONTROL.current),
    base = frameOffset(control),
    frame = {width, height};
  const plane = (offset, w, h, stride) => {
    const out = new Uint8Array(w * h);
    for (let y = 0; y < h; y++)
      memory.copy(out, y * w, base + offset + y * stride, base + offset + y * stride + w);
    return out;
  };
  frame.y = plane(0, width, height, FRAME_STRIDE);
  frame.cb = plane(LUMA_BYTES, width / 2, height / 2, FRAME_STRIDE / 2);
  frame.cr = plane(LUMA_BYTES + CHROMA_BYTES, width / 2, height / 2, FRAME_STRIDE / 2);
  return frame;
}

